#!/usr/bin/env python3
"""Generate a complete static map of the 91 MTH function leaves."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from nanlmind_hermes import mth_catalog, mth_leaves  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=str(ROOT / "docs" / "MTH_FUNCTION_TREE.md"))
    args = parser.parse_args()
    mth_leaves.reset_cache()
    with tempfile.TemporaryDirectory() as tmp:
        store = mth_leaves.LeafStore(Path(tmp) / "state")
        audit = store.ensure_function_tree()
    kernels = {kernel.kernel_id: kernel for kernel in mth_catalog.kernels()}
    lines = [
        "# MTH function tree map",
        "",
        "Generated by `scripts/mth_function_tree_report.py` from the bundled",
        "91-kernel manifest. Every kernel is one immutable function leaf with a",
        "family hub, source/fixture digests, data/operator/WordNet links and a",
        "NaN16 executable image.",
        "",
        "## Audit",
        "",
        "```json",
        json.dumps({key: audit[key] for key in (
            "expected", "linked", "missing", "extra", "duplicate_aliases",
            "digest_mismatches", "orphans", "ancestry_failures",
            "image_failures", "images_verified", "complete")}, indent=2),
        "```",
        "",
        "## Families",
        "",
        "| family | kernels |",
        "|---|---:|",
    ]
    for family, count in audit["family_counts"].items():
        lines.append("| `" + family + "` | " + str(count) + " |")
    lines.extend([
        "",
        "## Every kernel leaf",
        "",
        "| kernel | family | precision | shape | workspace | mode | leaf alias |",
        "|---|---|---|---|---:|---|---|",
    ])
    for kernel_id in sorted(kernels, key=lambda value: (kernels[value].family, value)):
        kernel = kernels[kernel_id]
        lines.append(
            "| `" + kernel_id + "` | `" + kernel.family + "` | `" +
            kernel.precision + "` | `" + "x".join(str(x) for x in kernel.shape) +
            "` | " + str(kernel.workspace_words) + " | `" +
            kernel.execution_mode + "` | `kernel:" + kernel_id + "` |")
    lines.append("")
    target = Path(args.output)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"output": str(target), "kernels": len(kernels),
                      "complete": audit["complete"],
                      "images_verified": audit["images_verified"]}, sort_keys=True))
    mth_leaves.reset_cache()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
